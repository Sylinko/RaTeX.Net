"""Generate target-specific notices using Cargo and the pinned Rust inventory."""

import argparse
import hashlib
import html
import json
import os
from pathlib import Path
import re
import subprocess
import sys


def read_text(path):
    return path.read_text(encoding="utf-8-sig")


def generate(root, rid):
    """Collect normal dependencies and the selected target's runtime notices."""
    config = json.loads(read_text(root / "build/native.json"))
    platform = "linux" if rid.startswith("linux-") else "mac"
    update_script = f"build/update-{platform}-notices.sh"
    target = config["targets"][rid]["target"]
    toolchain = config["toolchain"]
    upstream = root / "artifacts/upstream" / ("RaTeX-" + config["commit"])
    lock_bytes = (root / "build/Cargo.lock").read_bytes()
    lock_hash = hashlib.sha256(lock_bytes).hexdigest().upper()
    upstream_lock = upstream / "Cargo.lock"
    if not upstream_lock.is_file() or upstream_lock.read_bytes() != lock_bytes:
        raise RuntimeError(f"Run build/build-{platform}-native.sh first to prepare the pinned source and Cargo.lock.")

    environment = os.environ.copy()
    for name in ("RUSTFLAGS", "CARGO_ENCODED_RUSTFLAGS", "RUSTC_WRAPPER"):
        environment[name] = ""

    def run(*arguments):
        return subprocess.run(
            arguments, check=True, capture_output=True, text=True,
            encoding="utf-8", env=environment,
        ).stdout.strip()

    metadata = json.loads(run(
        "cargo", "+" + toolchain, "metadata",
        "--manifest-path", str(upstream / "crates/ratex-ffi/Cargo.toml"),
        "--format-version", "1", "--locked", "--filter-platform", target,
    ))
    sysroot = Path(run("rustc", "+" + toolchain, "--print", "sysroot"))
    rust_version = run("rustc", "+" + toolchain, "--version")

    texts = []
    text_ids = {}
    output = [f"""RaTeX.Net - third-party notices
==============================

Generated by {update_script}. Do not edit this file by hand.
Regenerate with: bash {update_script} {rid}
Check with:      bash {update_script} {rid} --check

RaTeX.Net's own license: LICENSE (MIT).
The notices below do not change the licenses of the individual components.

RaTeX and KaTeX fonts
--------------------
RaTeX: https://github.com/erweixin/RaTeX
Pinned commit: {config['commit']}
Copyright and full MIT license: licenses/RaTeX-MIT.txt

Unmodified KaTeX fonts embedded in RaTeX.Avalonia:
  Source and copyright notices: licenses/KaTeX-fonts-NOTICE.txt
  Full SIL Open Font License 1.1: licenses/SIL-OFL-1.1.txt
The fonts are licensed under OFL-1.1, independently of the MIT-licensed code.

Native dependencies
-------------------
Target: {target}
build/Cargo.lock SHA-256: {lock_hash}
Includes normal dependencies reachable from ratex-ffi for this target.
Build-only dependencies, procedural macros and dev dependencies are excluded.
Each file below refers to its full, unmodified text in the appendix.
MIT is selected where the upstream license offers it as an alternative.
Separate copyright and attribution notices are retained. Unfamiliar license
expressions stop generation for review.
"""]

    def add_component(name, expression, source, files):
        if expression.strip() in (
            "MIT", "MIT OR Apache-2.0", "Apache-2.0 OR MIT", "MIT/Apache-2.0",
            "Unlicense OR MIT", "Zlib OR Apache-2.0 OR MIT",
            "0BSD OR MIT OR Apache-2.0", "MIT OR Zlib OR Apache-2.0",
        ):
            selected = "MIT"
            pattern = r"LICEN[CS]E([._-]MIT)?(\.(txt|md))?"
        elif expression.strip() == "Unicode-3.0":
            selected = "Unicode-3.0"
            pattern = r"LICENSE[._-]UNICODE(\.(txt|md))?"
        else:
            raise RuntimeError(f"Review the license selection for {name}: {expression}")

        license_files = [
            file for file in files
            if file[2] or re.fullmatch(pattern, file[0], re.I)
        ]
        if not license_files:
            raise RuntimeError(f"Missing {selected} license text for {name}.")
        for file_name, text, _ in license_files:
            if selected == "MIT" and (
                "Permission is hereby granted, free of charge" not in text
                or "TERMS AND CONDITIONS FOR USE, REPRODUCTION, AND DISTRIBUTION" in text
            ):
                raise RuntimeError(f"Review the MIT license text for {name} ({file_name}).")

        output.append(f"\n{name} | {selected}\nSource: {source}\n")
        for file in sorted(files, key=lambda item: item[0].casefold()):
            file_name, text, _ = file
            if file not in license_files and not re.match(r"^(COPYRIGHT|COPYING|NOTICE)([._-]|$)", file_name, re.I):
                continue
            text = text.replace("\r\n", "\n").strip()
            if not text:
                raise RuntimeError(f"Empty license/notice text for {name} ({file_name}).")
            if text not in text_ids:
                texts.append(text)
                text_ids[text] = len(texts)
            output.append(f"  {file_name}: TEXT {text_ids[text]:03d}\n")

    packages = {package["id"]: package for package in metadata["packages"]}
    nodes = {node["id"]: node for node in metadata["resolve"]["nodes"]}
    ffi = [package for package in packages.values() if package["name"] == "ratex-ffi"]
    if len(ffi) != 1:
        raise RuntimeError("Expected exactly one ratex-ffi package.")
    pending = [ffi[0]["id"]]
    visited = set()
    while pending:
        package_id = pending.pop()
        if package_id in visited:
            continue
        visited.add(package_id)
        for dependency in nodes[package_id]["deps"]:
            normal = any(kind["kind"] is None for kind in dependency["dep_kinds"])
            macro = any("proc-macro" in item["kind"] for item in packages[dependency["pkg"]]["targets"])
            if normal and not macro:
                pending.append(dependency["pkg"])

    dependencies = sorted(
        (packages[key] for key in visited if packages[key]["source"]),
        key=lambda package: (package["name"], package["version"]),
    )
    if not dependencies:
        raise RuntimeError("No native dependencies found; review the dependency graph.")
    for package in dependencies:
        directory = Path(package["manifest_path"]).parent
        paths = {
            path for path in directory.iterdir()
            if path.is_file() and re.match(r"^(LICENSE|LICENCE|COPYING|COPYRIGHT|NOTICE|UNLICENSE)([._-]|$)", path.name, re.I)
        }
        declared = package.get("license_file")
        if declared:
            declared = directory / declared
            paths.add(declared)
        files = [
            (path.relative_to(directory).as_posix(), read_text(path), path == declared)
            for path in sorted(paths)
        ]
        add_component(
            f"{package['name']} {package['version']}", package["license"],
            package.get("repository") or package["source"], files,
        )
    for package_id in visited:
        package = packages[package_id]
        if package["source"] is None and (
            package_id not in metadata["workspace_members"]
            or not package["name"].startswith("ratex-")
            or package["license"] != "MIT"
        ):
            raise RuntimeError(f"Path dependency {package['name']} needs explicit license handling.")

    copyright_path = sysroot / "share/doc/rust/COPYRIGHT-library.html"
    if not copyright_path.is_file():
        raise RuntimeError(f"Install Rust notices with: rustup component add rust-docs --toolchain {toolchain}")
    document = read_text(copyright_path)
    if "Copyright notices for The Rust Standard Library" not in document or "<pre>" not in document:
        raise RuntimeError("Rust standard-library notice format changed.")
    output.append(f"\nRust standard library\n---------------------\nToolchain: {rust_version}\n")
    output.append("""Source: COPYRIGHT-library.html and licenses/ from the pinned Rust toolchain.
Includes in-tree notices applicable to Windows/macOS/Linux and external crates present in
the target runtime library inventory. Test, macro and profiling support are
excluded. Where the inventory lists several versions of a runtime crate,
their notices are retained conservatively.
""")

    in_tree = document.split('<h2 id="out-of-tree-dependencies">')[0]
    entries = re.findall(
        r"<b>File/Directory:</b>\s*<code>(.*?)</code>.*?<p><b>License:</b>\s*(.*?)</p>(.*?)(?=<p><b>Exceptions:|</div>)",
        in_tree, re.S,
    )
    if not entries or len(entries) != in_tree.count("<b>File/Directory:</b>"):
        raise RuntimeError("Rust in-tree copyright format changed.")
    for path, expression, body in entries:
        path = html.unescape(path).strip()
        if path == "library/std/src/sys/sync/mutex/fuchsia.rs":
            continue
        copyrights = [html.unescape(value).strip() for value in re.findall(r"<b>Copyright:</b>\s*(.*?)</p>", body, re.S)]
        if not copyrights:
            raise RuntimeError(f"Missing Rust attribution for {path}.")
        license_id = "Unicode-3.0" if html.unescape(expression).strip() == "Unicode-3.0" else "MIT"
        text = read_text(sysroot / f"share/doc/rust/licenses/{license_id}.txt")
        text = re.sub(r"^Copyright \(c\) <year> <copyright holders>\r?\n", "", text, flags=re.M)
        add_component(f"Rust in-tree: {path}", html.unescape(expression).strip(), "https://github.com/rust-lang/rust", [
            ("COPYRIGHT", "\n".join(copyrights), False),
            ("LICENSE-" + license_id.replace("-3.0", ""), text, False),
        ])

    excluded = {"getopts", "test", "proc-macro", "rustc-literal-escaper", "profiler-builtins"}
    runtime_names = set()
    for path in (sysroot / f"lib/rustlib/{target}/lib").glob("lib*.rlib"):
        match = re.fullmatch(r"lib(.+)-[a-f0-9]+\.rlib", path.name)
        if match:
            runtime_names.add(match[1].replace("_", "-"))
    runtime_names -= excluded
    if not {"std", "core"} <= runtime_names:
        raise RuntimeError("Cannot read the target Rust runtime inventory.")
    in_tree_names = {
        "alloc", "compiler-builtins", "core", "panic-abort", "panic-unwind", "std",
        "std-detect", "sysroot", "unwind", "rustc-std-workspace-alloc",
        "rustc-std-workspace-core", "rustc-std-workspace-std",
    }
    missing = runtime_names - in_tree_names
    for inventory_name in ("COPYRIGHT-library.html", "COPYRIGHT.html"):
        if not missing:
            break
        inventory = document
        if inventory_name == "COPYRIGHT.html":
            # The library-only inventory omits some target backtrace dependencies.
            inventory = read_text(sysroot / "share/doc/rust" / inventory_name)
            output.append("\nSupplemental target runtime entries from COPYRIGHT.html:\n")
        matched = set()
        for name, version, body in re.findall(r"<h3>[^<]*?([a-z0-9_-]+)-([0-9][^<]*)</h3>(.*?)(?=<h3>|</body>)", inventory, re.S):
            normalized_name = name.replace("_", "-")
            if normalized_name not in missing:
                continue
            expression = html.unescape(re.search(r"<b>License:</b>\s*(.*?)</p>", body, re.S)[1]).strip()
            source = html.unescape(re.search(r'<b>URL:</b>\s*<a href="([^"]+)"', body)[1])
            files = [
                (html.unescape(re.sub(r"<[^>]+>", "", title)), html.unescape(text), False)
                for title, text in re.findall(r"<summary>(.*?)</summary>\s*<pre>\s*(.*?)\s*</pre>", body, re.S)
            ]
            add_component(f"{name} {version} (Rust runtime)", expression, source, files)
            matched.add(normalized_name)
        missing -= matched
    if missing:
        raise RuntimeError("Missing Rust runtime copyright entries: " + ", ".join(sorted(missing)))
    output.append("\nFull license and notice texts\n============================\n")
    for index, text in enumerate(texts, 1):
        output.append(f"\n===== TEXT {index:03d} =====\n{text}\n")
    result = "".join(output).replace("\r\n", "\n").rstrip() + "\n"
    if "<year>" in result or "<copyright holders>" in result:
        raise RuntimeError("Unresolved license template placeholders.")
    for path in ("LICENSE", "licenses/RaTeX-MIT.txt", "licenses/KaTeX-fonts-NOTICE.txt", "licenses/SIL-OFL-1.1.txt"):
        if not (root / path).is_file():
            raise RuntimeError(f"Missing referenced file: {path}")
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("rid", choices=("osx-arm64", "osx-x64", "linux-x64", "linux-arm64"))
    parser.add_argument("--check", action="store_true")
    arguments = parser.parse_args()
    root = Path(__file__).resolve().parent.parent
    result = generate(root, arguments.rid)
    notice_path = Path("licenses") / f"THIRD_PARTY_NOTICES.{arguments.rid}.txt"
    destination = root / notice_path
    if arguments.check:
        if not destination.is_file() or read_text(destination) != result:
            platform = "linux" if arguments.rid.startswith("linux-") else "mac"
            raise RuntimeError(f"{notice_path.as_posix()} is stale. Run bash build/update-{platform}-notices.sh {arguments.rid}.")
        print("Third-party notices are up to date.")
    else:
        destination.parent.mkdir(parents=True, exist_ok=True)
        with destination.open("w", encoding="utf-8", newline="\n") as stream:
            stream.write(result)
        print(f"Generated {notice_path.as_posix()}.")


if __name__ == "__main__":
    try:
        main()
    except subprocess.CalledProcessError as error:
        print(error.stderr.strip(), file=sys.stderr)
        sys.exit(1)
    except (OSError, RuntimeError) as error:
        print(error, file=sys.stderr)
        sys.exit(1)
