#Requires -Version 7.0
param([switch]$Check)

$ErrorActionPreference = 'Stop'
$root = Split-Path $PSScriptRoot -Parent
$config = Get-Content (Join-Path $PSScriptRoot 'native.json') -Raw | ConvertFrom-Json
$RuntimeIdentifier = 'win-x64'
$nativeTarget = $config.targets.$RuntimeIdentifier.target
$upstream = Join-Path $root "artifacts/upstream/RaTeX-$($config.commit)"
$lockPath = Join-Path $PSScriptRoot 'Cargo.lock'
$lockHash = (Get-FileHash $lockPath -Algorithm SHA256).Hash
if (!(Test-Path "$upstream/Cargo.lock") -or (Get-FileHash "$upstream/Cargo.lock" -Algorithm SHA256).Hash -ne $lockHash) {
    throw 'Run build/build-windows-native.ps1 or build/build-mac-native.sh first to prepare the pinned upstream and Cargo.lock.'
}

$savedFlags = $env:RUSTFLAGS
$savedEncoded = $env:CARGO_ENCODED_RUSTFLAGS
$savedWrapper = $env:RUSTC_WRAPPER
try {
    $env:RUSTFLAGS = ''
    $env:CARGO_ENCODED_RUSTFLAGS = ''
    $env:RUSTC_WRAPPER = ''
    $metadataJson = & cargo "+$($config.toolchain)" metadata --manifest-path "$upstream/crates/ratex-ffi/Cargo.toml" --format-version 1 --locked --filter-platform $nativeTarget
    if ($LASTEXITCODE) { throw 'Cargo metadata failed.' }
    $metadata = $metadataJson | ConvertFrom-Json
    $sysroot = & rustc "+$($config.toolchain)" --print sysroot
    if ($LASTEXITCODE) { throw 'Cannot locate the pinned Rust toolchain.' }
    $rustVersion = & rustc "+$($config.toolchain)" --version
    if ($LASTEXITCODE) { throw 'Cannot identify the pinned Rust toolchain.' }
} finally {
    $env:RUSTFLAGS = $savedFlags
    $env:CARGO_ENCODED_RUSTFLAGS = $savedEncoded
    $env:RUSTC_WRAPPER = $savedWrapper
}

$texts = [System.Collections.Generic.List[string]]::new()
$textIds = [System.Collections.Generic.Dictionary[string, int]]::new([System.StringComparer]::Ordinal)
function Add-NoticeText([string]$Value) {
    $value = $Value.Replace("`r`n", "`n").Trim()
    if (!$value) { throw 'An empty license/notice file needs review.' }
    if (!$textIds.ContainsKey($value)) {
        $texts.Add($value)
        $textIds.Add($value, $texts.Count)
    }
    return ('TEXT {0:D3}' -f $textIds[$value])
}

function Add-Component([string]$Name, [string]$Expression, [string]$Source, [object[]]$Files) {
    # Deliberately handle only reviewed expressions, rather than guessing how
    # an unfamiliar SPDX expression or an AND/exception clause can be reduced.
    $selected = switch -Regex ($Expression.Trim()) {
        '^(MIT|MIT OR Apache-2\.0|Apache-2\.0 OR MIT|MIT/Apache-2\.0|Unlicense OR MIT|Zlib OR Apache-2\.0 OR MIT)$' { 'MIT'; break }
        '^Unicode-3\.0$' { 'Unicode-3.0'; break }
        default { throw "Review the license selection for ${Name}: $Expression" }
    }
    $licensePattern = if ($selected -eq 'MIT') {
        '^LICEN[CS]E([._-]MIT)?(\.(txt|md))?$'
    } else {
        '^LICENSE[._-]UNICODE(\.(txt|md))?$'
    }
    $licenseFiles = @($Files | Where-Object { $_.Name -match $licensePattern -or $_.DeclaredLicense })
    if (!$licenseFiles.Count) { throw "Missing $selected license text for $Name." }
    foreach ($file in $licenseFiles) {
        if ($selected -eq 'MIT' -and ($file.Text -notmatch 'Permission is hereby granted, free of charge' -or $file.Text -match 'TERMS AND CONDITIONS FOR USE, REPRODUCTION, AND DISTRIBUTION')) {
            throw "Review the MIT license text for $Name ($($file.Name))."
        }
    }
    [void]$output.AppendLine("`n$Name | $selected")
    [void]$output.AppendLine("Source: $Source")
    # Keep separate attribution files even when their names do not mention MIT.
    $retained = @($Files | Where-Object { $_ -in $licenseFiles -or $_.Name -match '^(COPYRIGHT|COPYING|NOTICE)([._-]|$)' } | Sort-Object Name)
    foreach ($file in $retained) {
        $reference = Add-NoticeText $file.Text
        [void]$output.AppendLine("  $($file.Name): $reference")
    }
}

$output = [System.Text.StringBuilder]::new()
[void]$output.AppendLine(@"
RaTeX.Net - third-party notices
==============================

Generated by build/update-windows-notices.ps1. Do not edit this file by hand.
Regenerate with: pwsh -File build/update-windows-notices.ps1
Check with:      pwsh -File build/update-windows-notices.ps1 -Check

RaTeX.Net's own license: LICENSE (MIT).
The notices below do not change the licenses of the individual components.

RaTeX and KaTeX fonts
--------------------
RaTeX: https://github.com/erweixin/RaTeX
Pinned commit: $($config.commit)
Copyright and full MIT license: licenses/RaTeX-MIT.txt

Unmodified KaTeX fonts embedded in RaTeX.Avalonia:
  Source and copyright notices: licenses/KaTeX-fonts-NOTICE.txt
  Full SIL Open Font License 1.1: licenses/SIL-OFL-1.1.txt
The fonts are licensed under OFL-1.1, independently of the MIT-licensed code.

Native dependencies
-------------------
Target: $nativeTarget
build/Cargo.lock SHA-256: $lockHash
Includes normal dependencies reachable from ratex-ffi for this target.
Build-only dependencies, procedural macros and dev dependencies are excluded.
Each file below refers to its full, unmodified text in the appendix.
MIT is selected where the upstream license offers it as an alternative.
Separate copyright and attribution notices are retained. Unfamiliar license
expressions stop generation for review.
"@)

$packages = @{}
$nodes = @{}
foreach ($package in $metadata.packages) { $packages[$package.id] = $package }
foreach ($node in $metadata.resolve.nodes) { $nodes[$node.id] = $node }
$ffi = @($metadata.packages | Where-Object name -eq 'ratex-ffi')
if ($ffi.Count -ne 1) { throw 'Expected exactly one ratex-ffi package.' }
$pending = [System.Collections.Generic.Queue[string]]::new()
$pending.Enqueue($ffi[0].id)
$visited = [System.Collections.Generic.HashSet[string]]::new()
while ($pending.Count) {
    $id = $pending.Dequeue()
    if (!$visited.Add($id)) { continue }
    foreach ($dependency in $nodes[$id].deps) {
        $normal = $dependency.dep_kinds | Where-Object { $null -eq $_.kind }
        $macro = $packages[$dependency.pkg].targets | Where-Object { $_.kind -contains 'proc-macro' }
        if ($normal -and !$macro) {
            $pending.Enqueue($dependency.pkg)
        }
    }
}

$dependencies = @($visited | ForEach-Object { $packages[$_] } | Where-Object source | Sort-Object name, version)
if (!$dependencies.Count) { throw 'No native dependencies found; review the dependency graph.' }
foreach ($package in $dependencies) {
    $directory = Split-Path $package.manifest_path -Parent
    $paths = @(Get-ChildItem $directory -File | Where-Object Name -Match '^(LICENSE|LICENCE|COPYING|COPYRIGHT|NOTICE|UNLICENSE)([._-]|$)' | Select-Object -ExpandProperty FullName)
    $declaredLicense = $null
    if ($package.license_file) {
        $declaredLicense = if ([System.IO.Path]::IsPathRooted($package.license_file)) { $package.license_file } else { Join-Path $directory $package.license_file }
        $paths += $declaredLicense
    }
    $files = @(foreach ($path in ($paths | Sort-Object -Unique)) {
        [pscustomobject]@{
            Name = [System.IO.Path]::GetRelativePath($directory, $path).Replace('\', '/')
            Text = Get-Content -LiteralPath $path -Raw
            DeclaredLicense = $path -eq $declaredLicense
        }
    })
    $source = if ($package.repository) { $package.repository } else { $package.source }
    Add-Component "$($package.name) $($package.version)" $package.license $source $files
}
foreach ($package in ($visited | ForEach-Object { $packages[$_] } | Where-Object { !$_.source })) {
    # Only the MIT-licensed RaTeX workspace crates share RaTeX-MIT.txt.
    if ($package.id -notin $metadata.workspace_members -or $package.name -notlike 'ratex-*' -or $package.license -ne 'MIT') {
        throw "Path dependency $($package.name) needs explicit license handling."
    }
}

$standardLibraryPath = Join-Path $sysroot 'share/doc/rust/COPYRIGHT-library.html'
if (!(Test-Path $standardLibraryPath)) {
    throw "Missing Rust standard-library notices. Install them with: rustup component add rust-docs --toolchain $($config.toolchain)"
}
$html = Get-Content -LiteralPath $standardLibraryPath -Raw
if ($html -notmatch 'Copyright notices for The Rust Standard Library' -or $html -notmatch '<pre>') {
    throw 'Rust standard-library notice format changed; review the HTML conversion.'
}
[void]$output.AppendLine("`nRust standard library`n---------------------")
[void]$output.AppendLine("Toolchain: $rustVersion")
[void]$output.AppendLine(@'
Source: COPYRIGHT-library.html and licenses/ from the pinned Rust toolchain.
Includes in-tree notices applicable to Windows/macOS and external crates present in
the target runtime library inventory. Test, macro and profiling support are
excluded. Where the inventory lists several versions of a runtime crate,
their notices are retained conservatively.
'@)

# Preserve the in-tree attributions, including Unicode's separate terms.
# The Fuchsia mutex file is the only platform-specific exception in this
# pinned document; do not silently discard new exceptions on toolchain updates.
$inTree = ($html -split '<h2 id="out-of-tree-dependencies">')[0]
$entries = [regex]::Matches($inTree, '(?s)<b>File/Directory:</b>\s*<code>(.*?)</code>.*?<p><b>License:</b>\s*(.*?)</p>(.*?)(?=<p><b>Exceptions:|</div>)')
if (!$entries.Count -or $entries.Count -ne [regex]::Matches($inTree, '<b>File/Directory:</b>').Count) {
    throw 'Rust in-tree copyright format changed.'
}
foreach ($entry in $entries) {
    $path = [System.Net.WebUtility]::HtmlDecode($entry.Groups[1].Value).Trim()
    if ($path -eq 'library/std/src/sys/sync/mutex/fuchsia.rs') { continue }
    $expression = [System.Net.WebUtility]::HtmlDecode($entry.Groups[2].Value).Trim()
    $copyrights = @([regex]::Matches($entry.Groups[3].Value, '(?s)<b>Copyright:</b>\s*(.*?)</p>') | ForEach-Object {
        [System.Net.WebUtility]::HtmlDecode($_.Groups[1].Value).Trim()
    })
    if (!$copyrights.Count) { throw "Missing Rust attribution for $path." }
    $licenseId = if ($expression -eq 'Unicode-3.0') { 'Unicode-3.0' } else { 'MIT' }
    $licenseText = Get-Content (Join-Path $sysroot "share/doc/rust/licenses/$licenseId.txt") -Raw
    # The MIT template's placeholder is replaced by the actual component's
    # copyrights in the separate COPYRIGHT notice, never invented authorship.
    $licenseText = $licenseText -replace '(?m)^Copyright \(c\) <year> <copyright holders>\r?\n', ''
    $files = @(
        [pscustomobject]@{ Name = 'COPYRIGHT'; Text = $copyrights -join "`n"; DeclaredLicense = $false }
        [pscustomobject]@{ Name = "LICENSE-$($licenseId -replace '-3.0$', '')"; Text = $licenseText; DeclaredLicense = $false }
    )
    Add-Component "Rust in-tree: $path" $expression 'https://github.com/rust-lang/rust' $files
}

# The sysroot rlibs bound the inventory to this target, unlike the copyright
# HTML's all-platform build/test dependency list. Retain candidate versions
# rather than infer exact crate versions from opaque rlib hashes.
$runtimeNames = @(Get-ChildItem (Join-Path $sysroot "lib/rustlib/$nativeTarget/lib") -Filter 'lib*.rlib' | ForEach-Object {
    if ($_.Name -match '^lib(.+)-[a-f0-9]+\.rlib$') { $Matches[1].Replace('_', '-') }
} | Where-Object { $_ -notin @('getopts', 'test', 'proc-macro', 'rustc-literal-escaper', 'profiler-builtins') })
if ('std' -notin $runtimeNames -or 'core' -notin $runtimeNames) { throw 'Cannot read the target Rust runtime inventory.' }
$matchedNames = [System.Collections.Generic.HashSet[string]]::new()
$sections = [regex]::Matches($html, '(?s)<h3>[^<]*?([a-z0-9_-]+)-([0-9][^<]*)</h3>(.*?)(?=<h3>|</body>)')
foreach ($section in $sections) {
    $name = $section.Groups[1].Value
    if ($name.Replace('_', '-') -notin $runtimeNames) { continue }
    [void]$matchedNames.Add($name.Replace('_', '-'))
    $version = $section.Groups[2].Value
    $body = $section.Groups[3].Value
    $expression = [System.Net.WebUtility]::HtmlDecode([regex]::Match($body, '<b>License:</b>\s*(.*?)</p>').Groups[1].Value).Trim()
    $source = [System.Net.WebUtility]::HtmlDecode([regex]::Match($body, '<b>URL:</b>\s*<a href="([^"]+)"').Groups[1].Value)
    $files = @([regex]::Matches($body, '(?s)<summary>(.*?)</summary>\s*<pre>\s*(.*?)\s*</pre>') | ForEach-Object {
        [pscustomobject]@{
            Name = [System.Net.WebUtility]::HtmlDecode(($_.Groups[1].Value -replace '<[^>]+>', ''))
            Text = [System.Net.WebUtility]::HtmlDecode($_.Groups[2].Value)
            DeclaredLicense = $false
        }
    })
    Add-Component "$name $version (Rust runtime)" $expression $source $files
}
$inTreeNames = @('alloc', 'compiler-builtins', 'core', 'panic-abort', 'panic-unwind', 'std', 'std-detect', 'sysroot', 'unwind', 'rustc-std-workspace-alloc', 'rustc-std-workspace-core', 'rustc-std-workspace-std')
foreach ($name in $runtimeNames) {
    if ($name -notin $inTreeNames -and !$matchedNames.Contains($name)) {
        throw "Missing copyright inventory entry for Rust runtime crate $name."
    }
}
[void]$output.AppendLine("`nFull license and notice texts`n============================")
for ($i = 0; $i -lt $texts.Count; $i++) {
    [void]$output.AppendLine(("`n===== TEXT {0:D3} =====" -f ($i + 1)))
    [void]$output.AppendLine($texts[$i])
}

$result = $output.ToString().Replace("`r`n", "`n").TrimEnd() + "`n"
if ($result -match '<year>|<copyright holders>') { throw 'Unresolved license template placeholders.' }
# Assert that conversion and deduplication never discard a license body.
foreach ($body in $texts) {
    if (!$result.Contains($body)) { throw 'A license/notice body was lost during generation.' }
}
foreach ($file in @('LICENSE', 'licenses/RaTeX-MIT.txt', 'licenses/KaTeX-fonts-NOTICE.txt', 'licenses/SIL-OFL-1.1.txt')) {
    if (!(Test-Path (Join-Path $root $file))) { throw "Missing referenced file: $file" }
}
$noticeFile = "licenses/THIRD_PARTY_NOTICES.$RuntimeIdentifier.txt"
$destination = Join-Path $root $noticeFile
if ($Check) {
    if (!(Test-Path $destination) -or (Get-Content $destination -Raw).Replace("`r`n", "`n") -cne $result) {
        throw "$noticeFile is stale. Run build/update-windows-notices.ps1 and commit the result."
    }
    Write-Host 'Third-party notices are up to date.'
} else {
    New-Item -ItemType Directory -Path (Split-Path $destination -Parent) -Force | Out-Null
    [System.IO.File]::WriteAllText($destination, $result.Replace("`n", "`r`n"), [System.Text.UTF8Encoding]::new($false))
    Write-Host "Generated $noticeFile ($($dependencies.Count) native dependencies, $($texts.Count) distinct notice texts)."
}
